#!/usr/bin/env bash
set -euo pipefail

if [[ $# -lt 1 || -z "$1" ]]; then
  echo "usage: check-baresip-adapter.sh <build-output-dir>" >&2
  exit 2
fi

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUTPUT_DIR="$1"
HEADER_DIR="$OUTPUT_DIR/headers"
FRAMEWORK_DIR="$OUTPUT_DIR/BaresipCore.xcframework"
SOURCE="$ROOT_DIR/Sources/SipSdk/SipClientBaresipV4.mm"
SDK_PATH="$(xcrun --sdk iphoneos --show-sdk-path)"

[[ -f "$HEADER_DIR/BaresipCore.h" ]] || {
  echo "Missing generated BaresipCore.h at $HEADER_DIR" >&2
  exit 1
}
[[ -f "$FRAMEWORK_DIR/Info.plist" ]] || {
  echo "Missing generated XCFramework at $FRAMEWORK_DIR" >&2
  exit 1
}

# Resolve slice directory names from the framework metadata instead of
# relying on names generated by xcodebuild.
slice_id_for() {
  python3 - "$FRAMEWORK_DIR/Info.plist" "$1" <<'PY'
import plistlib
import sys

with open(sys.argv[1], "rb") as source:
    info = plistlib.load(source)

requested = sys.argv[2]
for library in info.get("AvailableLibraries", []):
    if library.get("SupportedPlatform") != "ios":
        continue
    variant = library.get("SupportedPlatformVariant")
    if requested == "device" and variant is None:
        print(library["LibraryIdentifier"])
        raise SystemExit(0)
    if requested == "simulator" and variant == "simulator":
        print(library["LibraryIdentifier"])
        raise SystemExit(0)

raise SystemExit(f"Missing iOS {requested} slice in {sys.argv[1]}")
PY
}

DEVICE_SLICE="$(slice_id_for device)"
SIMULATOR_SLICE="$(slice_id_for simulator)"
DEVICE_LIBRARY="$FRAMEWORK_DIR/$DEVICE_SLICE/libBaresipCore.a"
SIMULATOR_LIBRARY="$FRAMEWORK_DIR/$SIMULATOR_SLICE/libBaresipCore.a"

[[ -f "$DEVICE_LIBRARY" ]] || { echo "Missing device library: $DEVICE_LIBRARY" >&2; exit 1; }
[[ -f "$SIMULATOR_LIBRARY" ]] || { echo "Missing Simulator library: $SIMULATOR_LIBRARY" >&2; exit 1; }

cat > "$OUTPUT_DIR/adapter-link-main.mm" <<'MAIN'
#import <Foundation/Foundation.h>
#import "SipClient.h"

int main(void)
{
    @autoreleasepool {
        SipClient *client =
            [[SipClient alloc] initWithUsername:@"ci" domain:@"example.invalid"];
        return client == nil;
    }
}
MAIN

link_adapter() {
  local sdk="$1"
  local target="$2"
  local library="$3"
  local label="$4"
  local sdk_path

  sdk_path="$(xcrun --sdk "$sdk" --show-sdk-path)"
  echo "==> Compile and link Baresip v4 adapter for $label ($target)"
  xcrun --sdk "$sdk" clang++ \
    -x objective-c++ \
    -std=c++17 \
    -fobjc-arc \
    -fblocks \
    -target "$target" \
    -isysroot "$sdk_path" \
    -I "$HEADER_DIR" \
    -I "$ROOT_DIR/Sources/SipSdk/include" \
    "$SOURCE" \
    "$OUTPUT_DIR/adapter-link-main.mm" \
    -x none "$library" \
    -framework Foundation \
    -framework UIKit \
    -framework CoreFoundation \
    -framework SystemConfiguration \
    -framework CoreAudio \
    -framework AudioToolbox \
    -framework AVFoundation \
    -framework CFNetwork \
    -framework CoreMedia \
    -framework CoreVideo \
    -framework CoreGraphics \
    -framework VideoToolbox \
    -framework QuartzCore \
    -framework CallKit \
    -lz -lm \
    -o "$OUTPUT_DIR/adapter-link-$label"
}

echo "==> Syntax-checking SipClientBaresipV4.mm against current Baresip headers"
xcrun --sdk iphoneos clang++ \
  -x objective-c++ \
  -std=c++17 \
  -fobjc-arc \
  -fblocks \
  -fsyntax-only \
  -target arm64-apple-ios15.0 \
  -isysroot "$SDK_PATH" \
  -I "$HEADER_DIR" \
  -I "$ROOT_DIR/Sources/SipSdk/include" \
  "$SOURCE"

link_adapter iphoneos "arm64-apple-ios15.0" "$DEVICE_LIBRARY" device-arm64
link_adapter iphonesimulator "arm64-apple-ios15.0-simulator" "$SIMULATOR_LIBRARY" simulator-arm64
link_adapter iphonesimulator "x86_64-apple-ios15.0-simulator" "$SIMULATOR_LIBRARY" simulator-x86_64
